--
--  EMBEDDING MODEL
--    Xenova/bge-small-en-v1.5 via @huggingface/transformers, mean-pooled and
--    L2-normalised. 384 dimensions.
--    If you swap the model, `vector(384)` must be resized to match or this
--    script will fail loudly on insert rather than silently returning garbage.
-- ═══════════════════════════════════════════════════════════════════════════

create extension if not exists vector with schema extensions;


-- ─── KNOWLEDGE CHUNKS ──────────────────────────────────────────────────────
-- One row per chunk of retrievable text. `doc_id` groups the chunks that came
-- from the same source document, so a product's three chunks share a doc_id.
create table if not exists public.knowledge_chunks (
  id         bigint generated by default as identity primary key,
  doc_id     text        not null,
  source     text        not null check (source in ('product','policy','service','faq')),
  title      text        not null default '',
  content    text        not null,
  url        text,
  metadata   jsonb       not null default '{}'::jsonb,
  embedding  extensions.vector(384),

  -- Generated from `content`, so keyword search can never drift from the text it
  -- indexes and re-indexing is a single UPDATE rather than a re-write.
  search     tsvector generated always as (to_tsvector('english', content)) stored,

  updated_at timestamptz not null default now()
);

comment on table public.knowledge_chunks is
  'Embedded chunks of the public knowledge base: the product catalogue plus the store policy documents. Never contains customer or order data - personal context is read from customer_orders at request time and injected separately, so nothing private is ever embedded.';

create index if not exists knowledge_chunks_embedding_idx
  on public.knowledge_chunks
  using hnsw (embedding extensions.vector_cosine_ops);

create index if not exists knowledge_chunks_search_idx
  on public.knowledge_chunks
  using gin (search);

create index if not exists knowledge_chunks_source_idx
  on public.knowledge_chunks (source);

-- Re-indexing deletes by (source, doc_id); this makes that a cheap scan.
create index if not exists knowledge_chunks_doc_idx
  on public.knowledge_chunks (source, doc_id);


-- ─── HYBRID RETRIEVAL ──────────────────────────────────────────────────────
--
--  Semantic search alone misses exact strings a customer is likely to type — a
--  model number, a pincode-format question, "7 day". Keyword search alone misses
--  paraphrase. This runs both and fuses the two rankings with Reciprocal Rank
--  Fusion, which needs no score calibration between the two systems (cosine
--  similarity and ts_rank are not comparable scales).
--
--  RRF: score = Σ 1 / (k + rank), k = 60.
--
--  Returns both component scores as well, so the caller can explain why a chunk
--  was chosen and set a sensible cutoff.
-- ────────────────────────────────────────────────────────────────────────────
create or replace function public.match_knowledge(
  p_embedding  extensions.vector(384),
  p_query      text default null,
  p_limit      integer default 6,
  p_sources    text[] default null
)
returns table (
  id            bigint,
  doc_id        text,
  source        text,
  title         text,
  content       text,
  url           text,
  metadata      jsonb,
  score         double precision,
  vector_score  double precision,
  keyword_score double precision
)
language sql
stable
set search_path = public, extensions
as $$
with semantic as (
  select
    c.id,
    (1 - (c.embedding <=> p_embedding))::double precision as score,
    row_number() over (order by c.embedding <=> p_embedding) as rank
  from public.knowledge_chunks c
  where c.embedding is not null
    and (p_sources is null or c.source = any (p_sources))
  order by c.embedding <=> p_embedding
  -- Over-fetch: fusion re-ranks, so the union can be wider than the final list.
  limit greatest(p_limit * 4, 20)
),
lexical as (
  select
    c.id,
    ts_rank_cd(c.search, websearch_to_tsquery('english', p_query))::double precision as score,
    row_number() over (
      order by ts_rank_cd(c.search, websearch_to_tsquery('english', p_query)) desc
    ) as rank
  from public.knowledge_chunks c
  where p_query is not null
    and c.search @@ websearch_to_tsquery('english', p_query)
    and (p_sources is null or c.source = any (p_sources))
  order by score desc
  limit greatest(p_limit * 4, 20)
),
fused as (
  select
    coalesce(s.id, l.id) as id,
    coalesce(1.0 / (60 + s.rank), 0) + coalesce(1.0 / (60 + l.rank), 0) as rrf
  from semantic s
  full outer join lexical l on s.id = l.id
)
select
  c.id,
  c.doc_id,
  c.source,
  c.title,
  c.content,
  c.url,
  c.metadata,
  f.rrf,
  s.score,
  l.score
from fused f
join public.knowledge_chunks c on c.id = f.id
left join semantic s on s.id = f.id
left join lexical l on l.id = f.id
order by f.rrf desc
limit p_limit;
$$;


-- ═══════════════════════════════════════════════════════════════════════════
--  ROW LEVEL SECURITY
-- ═══════════════════════════════════════════════════════════════════════════
--
--  The knowledge base is public documentation, and the server reaches it with
--  the service-role key anyway. RLS is enabled with a public read policy so that
--  if the anon key is ever exposed, a browser can read the marketing copy but
--  nothing else in the database.
-- ═══════════════════════════════════════════════════════════════════════════

alter table public.knowledge_chunks enable row level security;

drop policy if exists knowledge_public_read on public.knowledge_chunks;
create policy knowledge_public_read on public.knowledge_chunks
  for select using (true);

-- Only the server (service_role) writes.
revoke all on function public.match_knowledge(extensions.vector, text, integer, text[]) from anon, authenticated;
grant execute on function public.match_knowledge(extensions.vector, text, integer, text[]) to service_role;